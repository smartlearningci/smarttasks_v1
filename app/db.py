"""Ligação PostgreSQL e esquema inicial — RNF-04 e RNF-05 (V2).

As credenciais são fornecidas pelo ambiente, nunca guardadas no código.
O serviço 'db' é resolvido pela rede padrão do Docker Compose.
"""
import os


def connect():
    """Abre uma ligação nova; cada operação usa a sua transação.

    Variáveis PGHOST, PGPORT, PGDATABASE, PGUSER e PGPASSWORD evitam
    problemas com caracteres especiais numa password dentro de uma URL.
    """
    import psycopg
    from psycopg.rows import dict_row

    return psycopg.connect(
        host=os.environ["PGHOST"],
        port=os.environ.get("PGPORT", "5432"),
        dbname=os.environ["PGDATABASE"],
        user=os.environ["PGUSER"],
        password=os.environ["PGPASSWORD"],
        row_factory=dict_row,
    )


